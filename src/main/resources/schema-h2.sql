-- H2 建表脚本(可重复执行)
CREATE TABLE IF NOT EXISTS etf_info (
  code         VARCHAR(16) PRIMARY KEY,
  name         VARCHAR(64),
  market       VARCHAR(8),
  secid        VARCHAR(16),
  category     VARCHAR(32),
  defensive    BOOLEAN,
  benchmark    BOOLEAN,
  enabled      BOOLEAN,
  source       VARCHAR(16),
  latest_date  DATE,
  bar_count    INT,
  note         VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS daily_bar (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code      VARCHAR(16)  NOT NULL,
  trade_date DATE        NOT NULL,
  open      DOUBLE,
  high      DOUBLE,
  low       DOUBLE,
  close     DOUBLE,
  volume    DOUBLE,
  amount    DOUBLE,
  CONSTRAINT uk_bar_code_date UNIQUE (code, trade_date)
);
CREATE INDEX IF NOT EXISTS idx_bar_code_date ON daily_bar (code, trade_date);

CREATE TABLE IF NOT EXISTS factor_def (
  factor_id       VARCHAR(32) PRIMARY KEY,
  factor_name     VARCHAR(128),
  factor_category VARCHAR(32),
  scope           TEXT,
  meaning         TEXT,
  formula         TEXT,
  required_data   TEXT,
  input_freq      VARCHAR(128),
  calc_freq       VARCHAR(128),
  calc_params     TEXT,
  min_history     TEXT,
  output_desc     TEXT,
  direction       TEXT,
  data_caliber    TEXT,
  missing_policy  TEXT,
  outlier_policy  TEXT,
  standardization TEXT,
  neutralization  TEXT,
  availability    TEXT,
  source_name     VARCHAR(255),
  source_url      VARCHAR(512),
  source_detail   TEXT,
  candidate_source TEXT,
  limits          TEXT,
  table_version   VARCHAR(8)
);

CREATE TABLE IF NOT EXISTS strategy_config (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  strategy_code      VARCHAR(64),
  name               VARCHAR(128),
  version            INT,
  momentum_window    INT,
  holding_count      INT,
  rebalance_freq     VARCHAR(16),
  defensive_enabled  BOOLEAN,
  defensive_threshold DOUBLE,
  defensive_mode     VARCHAR(8),
  defensive_asset    VARCHAR(16),
  trend_filter_enabled BOOLEAN,
  trend_window       INT,
  trend_threshold    DOUBLE,
  commission_rate    DOUBLE,
  minimum_commission DOUBLE,
  slippage_rate      DOUBLE,
  initial_cash       DOUBLE,
  benchmark_asset    VARCHAR(16),
  universe_note      TEXT,
  note               TEXT,
  params_json        TEXT,
  created_at         TIMESTAMP
);

CREATE TABLE IF NOT EXISTS backtest_run (
  run_id             VARCHAR(48) PRIMARY KEY,
  purpose            VARCHAR(32),
  status             VARCHAR(16),
  data_type          VARCHAR(16),
  strategy_code      VARCHAR(64),
  strategy_version   VARCHAR(16),
  strategy_config_id BIGINT,
  config_json        TEXT,
  start_date         DATE,
  end_date           DATE,
  initial_cash       DOUBLE,
  benchmark          VARCHAR(64),
  message            TEXT,
  note               TEXT,
  created_at         TIMESTAMP,
  finished_at        TIMESTAMP
);

CREATE TABLE IF NOT EXISTS equity_point (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id         VARCHAR(48),
  series_id      VARCHAR(16),
  trade_date     DATE,
  nav            DOUBLE,
  cash           DOUBLE,
  position_value DOUBLE
);
CREATE INDEX IF NOT EXISTS idx_eq_run ON equity_point (run_id, series_id, trade_date);

CREATE TABLE IF NOT EXISTS position_snapshot (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id     VARCHAR(48),
  series_id  VARCHAR(16),
  trade_date DATE,
  asset_id   VARCHAR(16),
  quantity   DOUBLE,
  weight     DOUBLE
);
CREATE INDEX IF NOT EXISTS idx_pos_run ON position_snapshot (run_id, series_id, trade_date);

CREATE TABLE IF NOT EXISTS trade_record (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id         VARCHAR(48),
  series_id      VARCHAR(16),
  signal_time    VARCHAR(40),
  execution_time VARCHAR(40),
  asset_id       VARCHAR(16),
  side           VARCHAR(8),
  quantity       DOUBLE,
  price          DOUBLE,
  fee            DOUBLE,
  slippage_cost  DOUBLE,
  status         VARCHAR(16),
  reason         TEXT
);
CREATE INDEX IF NOT EXISTS idx_trd_run ON trade_record (run_id, series_id, execution_time);

CREATE TABLE IF NOT EXISTS decision_record (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id              VARCHAR(48),
  signal_date         DATE,
  executed            BOOLEAN,
  defensive_triggered BOOLEAN,
  defensive_reason    VARCHAR(255),
  payload             TEXT
);
CREATE INDEX IF NOT EXISTS idx_dec_run ON decision_record (run_id, signal_date);

CREATE TABLE IF NOT EXISTS run_metric (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id       VARCHAR(48),
  series_id    VARCHAR(16),
  metric       VARCHAR(32),
  metric_value DOUBLE,
  unit         VARCHAR(16),
  definition   TEXT
);
CREATE INDEX IF NOT EXISTS idx_met_run ON run_metric (run_id, series_id);
